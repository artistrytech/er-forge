export const messages: Record<Lang, Record<MsgKey, string>> = { ja, en };

/** 初期言語はユーザーの環境設定に従う（X-01）。ja で始まるなら日本語、それ以外は英語 */
export function detectLang(languages: readonly string[]): Lang {
  for (const l of languages) {
    if (l.toLowerCase().startsWith("ja")) return "ja";
    // 最初の言語を優先する（リスト先頭が非日本語なら英語）
    return "en";
  }
  return "en";
}

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = messages[lang][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}
